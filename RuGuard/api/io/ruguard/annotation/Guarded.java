package io.ruguard.annotation;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Повесь эту аннотацию на метод или конструктор, который нужно защитить от декомпиляции.
 * 
 * ВАЖНО: Защищается только тот метод, на который повешена аннотация, а не весь класс целиком! 
 * Если нужно защитить весь класс, пометь этой аннотацией каждый его метод.
 * 
 * ВНИМАНИЕ ПРИ РАЗРАБОТКЕ МОДОВ (Fabric, Forge, NeoForge, Mixins):
 * 1. НЕ ставь @Guarded на методы-миксины (помеченные @Inject, @Redirect, @Overwrite, @ModifyArg и т.д.).
 *    Иначе игра вылетит при загрузке, так как система Mixin не сможет прочесть зашифрованный байткод.
 *    Решение: Создай свой защищенный метод и вызывай его из метода-миксина.
 * 2. НЕ ставь @Guarded на переопределенные методы игры (например, переопределения render(), tick(), use() и т.д.).
 * 
 * Пример использования:
 * 
 * @Guarded(Guarded.Level.STRONG)
 * public void myMethod() { ... }
 */
@Retention(RetentionPolicy.CLASS)
@Target({ElementType.METHOD, ElementType.CONSTRUCTOR})
public @interface Guarded {
    
    /**
     * Уровни защиты:
     */
    enum Level { 
        /** 
         * STANDARD: Обычное шифрование метода.
         * Влияние на производительность: Вообще не кушает ФПС (0% просадки). Идеально для частых/игровых методов.
         */
        STANDARD, 
        
        /** 
         * STRONG: Шифрование + жесткое запутывание кода (Control-Flow Flattening), чтобы взломщик сломал мозг.
         * Влияние на производительность: Почти не влияет на ФПС (около 1-2% просадки). Подходит для обычной игровой логики.
         */
        STRONG, 
        
        /** 
         * VIRTUALIZED: Метод переводится в наш собственный байткод и выполняется внутри защищенной библиотеки Rust (нативная виртуальная машина). Максимальная защита.
         * Влияние на производительность: Сильно кушает ФПС. Не используй в методах, которые вызываются каждый кадр (рендер, тики). Подходит для проверки лицензий, авторизации или редких вызовов.
         */
        VIRTUALIZED 
    }
    
    /**
     * Выбери уровень защиты. По умолчанию стоит STANDARD.
     */
    Level value() default Level.STANDARD;
}
